import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const sources = ['brand/logo-full-sedebar-expanded.svg', 'brand/logo-sidebar-colapse-and-favicon.svg'];
// Git checkout line endings differ between Windows, macOS and Linux CI.
const inputs = await Promise.all(
  sources.map(async (path) => (await readFile(new URL(path, root), 'utf8')).replace(/\r\n?/g, '\n')),
);
// The original CorelDRAW files remain the source of truth. Only path/rect
// geometry is exported: no XML DTD, editor metadata, external refs or IDs.
function artwork(source) {
  const viewBox = source.match(/viewBox="([\d .-]+)"/)?.[1];
  assert.ok(viewBox, 'SVG viewBox is required.');
  const classes = new Map(
    [...source.matchAll(/\.(fil\d+)\s*\{fill:(#[\da-f]+)(;fill-rule:nonzero)?\}/gi)].map(
      ([, name, color, nonzero]) => [
        name,
        {
          accent: ['#adce51', '#aacf4e'].includes(color.toLowerCase()),
          rule: nonzero ? 'nonzero' : 'evenodd',
        },
      ],
    ),
  );
  const paths = [...source.matchAll(/<(path|rect)\s+([^>]+)\/>/g)].map(([, tag, attributes]) => {
    const attrs = Object.fromEntries(
      [...attributes.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, key, value]) => [key, value]),
    );
    const style = classes.get(attrs.class);
    assert.ok(style, 'Unknown source fill class.');
    let d = attrs.d;
    if (tag === 'rect') {
      const [x, y, width, height] = ['x', 'y', 'width', 'height'].map((key) => Number(attrs[key]));
      assert.ok([x, y, width, height].every(Number.isFinite));
      d = `M${x} ${y}h${width}v${height}h${-width}z`;
    }
    assert.ok(d && /^[MmLlHhVvCcSsQqTtAaZz\d.,\s+-]+$/.test(d), 'Invalid path geometry.');
    return { d, ...style };
  });
  assert.ok(paths.length >= 3, 'Missing logo paths.');
  return { viewBox, paths };
}
const [full, compact] = inputs.map(artwork);
const revision = createHash('sha256').update(inputs.join('\n')).digest('hex').slice(0, 12);
const module = `// Generated by scripts/generate-brand.mjs from the original brand/*.svg.\nexport const brandRevision = '${revision}';\nexport const fullArtwork = ${JSON.stringify(full)} as const;\nexport const compactArtwork = ${JSON.stringify(compact)} as const;\n`;
const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${compact.viewBox}" fill-rule="nonzero"><style>.ink{fill:#0b0b0b}.accent{fill:#a6d44b}@media(prefers-color-scheme:dark){.ink{fill:#f5f7f8}}</style>${compact.paths.map(({ d, accent, rule }) => `<path class="${accent ? 'accent' : 'ink'}" fill-rule="${rule}" d="${d}"/>`).join('')}</svg>\n`;
const outputs = [
  ['packages/ui/src/brand-artwork.ts', module],
  ...['portal', 'auth', 'bag-filter', 'consumables'].map((app) => [
    `apps/${app}/public/favicon.svg`,
    favicon,
  ]),
];
// Format generated code using the repository's pinned formatter.
const { format } = await import('prettier');
for (const [path, value] of outputs) {
  const content = path.endsWith('.ts')
    ? await format(value, { parser: 'typescript', singleQuote: true, printWidth: 110 })
    : value;
  if (process.argv.includes('--check'))
    assert.equal(
      await readFile(new URL(path, root), 'utf8'),
      content,
      `${path} is stale; run pnpm brand:generate.`,
    );
  else await writeFile(new URL(path, root), content);
}
console.log(
  `Brand assets ${process.argv.includes('--check') ? 'verified' : 'generated'} (${revision}) in ${fileURLToPath(root)}.`,
);
